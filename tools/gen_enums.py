#!/usr/bin/env python3
"""Generate opt_enums.h from the vendored OpenPrintTag specification data.

The specification publishes machine-readable enum definitions, so the firmware's
name tables are generated rather than transcribed. Re-run after refreshing
spec-data/ from the upstream repository:

    python3 tools/gen_enums.py
"""

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec-data"
OUT = ROOT / "firmware" / "OpenPrintTagDryer" / "src" / "openprinttag" / "opt_enums.h"


def load(name):
    with (SPEC / f"{name}.yaml").open() as handle:
        return yaml.safe_load(handle)


def c_string(value):
    return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit_table(out, c_name, entries, label_key):
    """Emit a sorted key/name lookup table."""
    entries = sorted(entries, key=lambda item: item["key"])
    out.append(f"inline constexpr OptEnumEntry {c_name}[] = {{")
    for item in entries:
        label = item.get(label_key) or item.get("name") or str(item["key"])
        out.append(f"    {{{item['key']}, {c_string(label)}}},")
    out.append("};")
    out.append(f"inline constexpr size_t {c_name}Count = "
               f"sizeof({c_name}) / sizeof({c_name}[0]);")
    out.append("")


def main():
    material_types = load("material_type_enum")
    material_classes = load("material_class_enum")
    write_protection = load("write_protection_enum")
    tags = load("tags_enum")
    certifications = load("material_certifications_enum")

    out = [
        "// Generated by tools/gen_enums.py from spec-data/*.yaml -- do not edit.",
        "//",
        "// Enum value names from the OpenPrintTag specification",
        "// (https://github.com/OpenPrintTag/openprinttag-specification, MIT).",
        "",
        "#pragma once",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "namespace opt {",
        "",
        "struct OptEnumEntry {",
        "    uint16_t key;",
        "    const char *name;",
        "};",
        "",
    ]

    emit_table(out, "kMaterialTypes", material_types, "abbreviation")
    emit_table(out, "kMaterialClasses", material_classes, "name")
    emit_table(out, "kWriteProtection", write_protection, "name")
    emit_table(out, "kMaterialTags", tags, "name")
    emit_table(out, "kCertifications", certifications, "name")

    out += [
        "// Returns the specification name for a value, or nullptr when the value is",
        "// not one the specification defines. Unknown values are legal: the spec",
        "// allows new enum items to appear at any time, so callers render them",
        "// numerically instead of rejecting the tag.",
        "inline const char *enumName(const OptEnumEntry *table, size_t count,",
        "                            uint16_t key) {",
        "    for (size_t i = 0; i < count; ++i) {",
        "        if (table[i].key == key) {",
        "            return table[i].name;",
        "        }",
        "    }",
        "    return nullptr;",
        "}",
        "",
        "inline const char *materialTypeName(uint16_t key) {",
        "    return enumName(kMaterialTypes, kMaterialTypesCount, key);",
        "}",
        "",
        "inline const char *materialClassName(uint16_t key) {",
        "    return enumName(kMaterialClasses, kMaterialClassesCount, key);",
        "}",
        "",
        "inline const char *writeProtectionName(uint16_t key) {",
        "    return enumName(kWriteProtection, kWriteProtectionCount, key);",
        "}",
        "",
        "inline const char *materialTagName(uint16_t key) {",
        "    return enumName(kMaterialTags, kMaterialTagsCount, key);",
        "}",
        "",
        "// Reverse lookup, used by the provisioning form to turn a submitted",
        "// abbreviation such as \"PETG\" back into its enum value.",
        "inline bool materialTypeFromName(const char *name, uint16_t *out) {",
        "    if (name == nullptr) {",
        "        return false;",
        "    }",
        "    for (size_t i = 0; i < kMaterialTypesCount; ++i) {",
        "        const char *candidate = kMaterialTypes[i].name;",
        "        size_t j = 0;",
        "        while (candidate[j] != '\\0' && name[j] != '\\0' &&",
        "               candidate[j] == name[j]) {",
        "            ++j;",
        "        }",
        "        if (candidate[j] == '\\0' && name[j] == '\\0') {",
        "            *out = kMaterialTypes[i].key;",
        "            return true;",
        "        }",
        "    }",
        "    return false;",
        "}",
        "",
        "}  // namespace opt",
        "",
    ]

    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)}: "
          f"{len(material_types)} material types, {len(tags)} tags, "
          f"{len(certifications)} certifications")


if __name__ == "__main__":
    main()
